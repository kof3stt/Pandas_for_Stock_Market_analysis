import pandas as pd


df1 = pd.DataFrame(
    {
        "id": [2, 4, 7, 8, 12],
        "товар": ["ложка столовая", "нож", "вилка", "ложка чайная", "тарелка"],
        "количество": [1220, 2035, 890, 538, 240],
    }
)

df2 = pd.DataFrame(
    {
        "товар": ["ложка столовая", "нож", "вилка", "ножницы", "тарелка"],
        "цена": [100, 450, 140, 280, 390],
    }
)
df1 = df1.set_index("id")
df = df1.merge(df2, on="товар", how="inner")
print(df)
