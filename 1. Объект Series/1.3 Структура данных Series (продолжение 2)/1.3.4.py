import pandas as pd


d1 = {
    'ПАО "Россети"': 54_210_000_000,
    'ПАО "РусГидро"': 19_325_000_000,
    'ПАО "Юнипро"': 21_267_722_000,
}
srs1 = pd.Series(d1, name="Чистая прибыль за 2022 год, руб.")
d2 = {
    'ПАО "Россети"': 110_844_896_493.56,
    'ПАО "РусГидро"': 333_200_635_086.47,
    'ПАО "Юнипро"': 84_863_558_471.17,
}
srs2 = pd.Series(d2, name="Капитализация на конец 2022 года, в млн рублей")
srs = pd.Series(srs2 / srs1, name="P/E 2022 год")
srs = srs.round(1)
print(srs)
